let currentLanguage = localStorage.getItem('hreem_lang') || 'en';

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLanguage = lang;
  localStorage.setItem('hreem_lang', lang);
  document.documentElement.lang = lang;

  if (lang === 'mr') {
    document.body.classList.add('lang-mr');
  } else {
    document.body.classList.remove('lang-mr');
  }

  // Update DOM elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = TRANSLATIONS[lang][key];
      } else {
        el.textContent = TRANSLATIONS[lang][key];
      }
    }
  });

  // Update active UI state for language toggle buttons
  document.querySelectorAll('.lang-switcher-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Dispatch custom event for dynamic components (Products, Cart, Courses)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function getTranslation(key, defaultVal = '') {
  if (TRANSLATIONS[currentLanguage] && TRANSLATIONS[currentLanguage][key]) {
    return TRANSLATIONS[currentLanguage][key];
  }
  if (TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return defaultVal || key;
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLanguage);

  // Bind language switcher clicks
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-switcher-btn');
    if (btn) {
      const targetLang = btn.getAttribute('data-lang');
      setLanguage(targetLang);
    }
  });
});
